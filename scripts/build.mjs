import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
const githubBase = 'https://raw.githubusercontent.com/fanbuz/loon-speedtest-plugin/main/dist/';
const usage = 'GitHub Raw：npm run build；其他托管：npm run build -- --base-url https://host/对象目录/；本地脚本：npm run build:local';
let baseUrl;
let local = false;
let outputDir;
while (args.length) {
  const option = args.shift();
  if (option === '--base-url' && !baseUrl && args.length) baseUrl = args.shift();
  else if (option === '--local' && !local) local = true;
  else if (option === '--out-dir' && !outputDir && args.length) outputDir = args.shift();
  else throw new Error(usage);
}
if (baseUrl && local) throw new Error('远端和本地构建目标不能同时指定。' + usage);
if (!baseUrl && !local) baseUrl = githubBase;
let scriptPath = 'loon-speedtest.js';
if (baseUrl) {
  const base = new URL(baseUrl);
  if (!['http:', 'https:'].includes(base.protocol) || base.username || base.password || base.search || base.hash || !base.pathname.endsWith('/')) {
    throw new Error('base-url 必须为不含凭据、查询参数的 HTTP(S) 目录地址，并以 / 结尾');
  }
  scriptPath = new URL('loon-speedtest.js', base).href;
}
const sources = await Promise.all(['src/core.js', 'src/presentation.js', 'src/loon.js'].map(file => readFile(path.join(root, file), 'utf8')));
const { version } = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
if (baseUrl) {
  const remoteScript = new URL(scriptPath);
  remoteScript.searchParams.set('v', version);
  scriptPath = remoteScript.href;
}
const iconUrl = baseUrl ? new URL('icon.png?v=' + version, baseUrl).href : null;
const icon = await readFile(path.join(root, 'assets/icon.png'));
const destination = outputDir ? path.resolve(outputDir) : path.join(root, 'dist');
await mkdir(destination, { recursive: true });
await writeFile(path.join(destination, 'loon-speedtest.js'), '// Loon Speedtest v' + version + ' — generated by npm run build\n' + sources.join('\n;\n'));
const plugin = [
  '#!name = 节点速度测试',
  '#!author = fanbuz',
  '#!homepage = https://github.com/fanbuz/loon-speedtest-plugin',
  ...(baseUrl ? ['#!icon = ' + iconUrl] : []),
  '#!desc = v' + version + ' 指定节点的上传与下载速度测试，支持单路、并发和对比；默认合计 64 MB。',
  '#!loon_version = 3.2.1(745)',
  '#!date = 2026-10-17',
  '#!tag = 工具,测速',
  '',
  '[Argument]',
  'direction = select,"both","download","upload",tag=测试项目,desc=both 下载和上传 / download 仅下载 / upload 仅上传',
  'mode = select,"single","concurrent","compare",tag=测速模式,desc=single 单路 / concurrent 并发 / compare 顺序对比',
  'adaptive = switch,true,tag=自适应测量,desc=小块单路预热、动态分块；明确结束的瞬时故障最多恢复一次',
  'httpVersion = select,"auto","h2","h1",tag=测速 HTTP 版本,desc=auto 优先 h2，明确失败时允许一次 h1 兼容恢复',
  'node = input,"",tag=节点或策略组,desc=填写精确名称；留空时从运行入口获取；直连填 DIRECT',
  'test_source = select,"Apple CDN","Cloudflare","自定义",tag=下载测速源,desc=下载来源；自定义时填写下方 test_url',
  'test_url = input,"",tag=自定义下载地址 test_url,desc=仅选择自定义时有效；支持 HEAD 和 Range GET；范围声明可缺省',
  'upload_source = select,"Apple CDN","Cloudflare","自定义",tag=上传测速源,desc=上传来源；与下载独立选择',
  'upload_url = input,"",tag=自定义上传地址,desc=仅上传源选自定义时有效；须为接收二进制 POST 的测速接口',
  'concurrency = select,4,2,8,tag=并发请求数,desc=仅 concurrent 和 compare 模式使用',
  'duration = select,10,5,15,30,tag=正式测量时长（秒）,desc=不含预热；到期停止发新请求并等待在途请求完成',
  'warmup = select,2,0,1,3,5,tag=预热窗口（秒）,desc=到时停发并收尾；最多占本轮预算四分之一；不计平均速度',
  'chunkKB = select,4000,1000,250,64,tag=下载分块上限（KB）,desc=自适应从小块开始；关闭时按固定块大小请求',
  'uploadChunkKB = select,1000,250,64,4000,tag=上传分块上限（KB）,desc=与下载独立；自适应从小块开始',
  'maxMB = select,64,16,128,256,tag=总请求数据预算（十进制 MB）,desc=下载上传及对比各轮均分，包含预热；不含协议开销',
  'requestTimeout = select,10,5,3,15,tag=请求超时上限（秒）,desc=自适应正式阶段按块大小缩短等待，上限由此设置',
  'notify = switch,true,tag=完成后通知',
  '',
  '[Script]',
  // Loon's legacy binding passes these named values as $argument properties.
  // Keep free-text URLs/names out of query-string or JSON interpolation.
  'generic script-path=' + scriptPath + ', argument=[{direction},{mode},{adaptive},{httpVersion},{node},{test_source},{test_url},{upload_source},{upload_url},{concurrency},{duration},{warmup},{chunkKB},{uploadChunkKB},{maxMB},{requestTimeout},{notify}], tag=节点速度测试, img-url=arrow.up.arrow.down.system, timeout=420',
  ''
].join('\n');
await writeFile(path.join(destination, 'LoonSpeedtest.plugin'), plugin);
await writeFile(path.join(destination, 'icon.png'), icon);
console.log('已生成 ' + destination + ' 下的脚本和插件；脚本路径：' + scriptPath);
if (local) console.log('这是本地脚本引用配置。上传 GitHub/OSS 前需要重新运行远端构建。');
